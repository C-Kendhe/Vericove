import apiClient, { USE_MOCK_FALLBACK } from './api';
import { DEMO_RESEARCH_PAPERS } from '../data/demoResearch';

export const aiService = {
  /**
   * Analyzes free-form patient natural language to extract structured symptom entities
   * Non-diagnostic, strictly for health communication and personal organization.
   */
  async extractSymptoms(text) {
    try {
      const response = await apiClient.post('/ai/extract-symptoms', { text });
      return response.data || response;
    } catch (err) {
      if (USE_MOCK_FALLBACK) {
        // Intelligent client-side heuristic parser for demo
        const lower = text.toLowerCase();
        const extracted = [];
        const detectedTriggers = [];

        if (lower.includes('pelvic') || lower.includes('cramp') || lower.includes('period pain') || lower.includes('dysmenorrhea')) {
          extracted.push({
            name: "Pelvic / Menstrual Pain",
            bodyArea: "Pelvic",
            frequency: lower.includes('month') || lower.includes('cycle') ? "Cyclic (Monthly flare)" : "Intermittent",
            suspectedDuration: lower.includes('three months') || lower.includes('3 months') ? "3 months" : "Recurring",
            severityRatingEstimate: lower.includes('severe') || lower.includes('terrible') || lower.includes('unbearable') ? 8 : 6
          });
        }

        if (lower.includes('fatigue') || lower.includes('exhaust') || lower.includes('tired') || lower.includes('fog')) {
          extracted.push({
            name: "Persistent Fatigue & Low Vitality",
            bodyArea: "Whole Body / Energy",
            frequency: "Daily / Chronic",
            suspectedDuration: "3+ months",
            severityRatingEstimate: 7
          });
        }

        if (lower.includes('irregular') || lower.includes('missed period') || lower.includes('cycle')) {
          extracted.push({
            name: "Cycle Irregularity / Oligomenorrhea",
            bodyArea: "Reproductive",
            frequency: "Ongoing",
            suspectedDuration: "3 months",
            severityRatingEstimate: 5
          });
        }

        if (lower.includes('bloat') || lower.includes('stomach') || lower.includes('belly') || lower.includes('gut')) {
          extracted.push({
            name: "Abdominal Distension & Bloating",
            bodyArea: "Abdominal",
            frequency: "Post-prandial / Cyclic",
            suspectedDuration: "Recurring",
            severityRatingEstimate: 6
          });
        }

        if (lower.includes('migraine') || lower.includes('headache')) {
          extracted.push({
            name: "Hormone-Associated Migraine",
            bodyArea: "Head & Neurological",
            frequency: "Catamenial (Pre-menses)",
            suspectedDuration: "Recurring episodes",
            severityRatingEstimate: 8
          });
        }

        // If none explicitly matched, add a generic structured entry
        if (extracted.length === 0) {
          extracted.push({
            name: "Unspecified Health Discomfort",
            bodyArea: "Whole Body / Energy",
            frequency: "Recent onset",
            suspectedDuration: "Under review",
            severityRatingEstimate: 5
          });
        }

        const structuredSummary = `Patient reports a symptom constellation including ${extracted.map(e => e.name).join(', ')}. The clinical narrative highlights notable impact on daily stamina and perimenstrual worsening.`;

        const doctorQuestions = [
          "Could these recurrent symptoms reflect an underlying hormonal condition such as endometriosis or PCOS?",
          "Given the duration and cyclical nature, would a pelvic ultrasound or protocol-specific pelvic MRI be appropriate?",
          "Would evaluating a comprehensive hormone profile and serum ferritin (to rule out non-anemic iron deficiency) provide diagnostic clarity?",
          "How can we track symptom trends relative to my menstrual calendar over the next 2-3 cycles?"
        ];

        return {
          extractedSymptoms: extracted,
          structuredSummary,
          suggestedQuestionsForDoctor: doctorQuestions,
          followUpQuestions: [
            "Do your symptoms change predictably with different phases of your menstrual cycle?",
            "Have you noticed standard over-the-counter anti-inflammatories providing noticeable relief?",
            "Does the discomfort radiate to your lower back, hips, or legs?"
          ],
          disclaimer: "This analysis is generated by AI to assist in organizing your personal symptom observations for clinical discussions. Vericove does not diagnose medical conditions or prescribe interventions."
        };
      }
      throw err;
    }
  },

  /**
   * Research-grounded AI assistant: answers informational health questions with citations
   */
  async askResearchAssistant(query) {
    try {
      const response = await apiClient.post('/ai/research-chat', { query });
      return response.data || response;
    } catch (err) {
      if (USE_MOCK_FALLBACK) {
        const q = query.toLowerCase();
        let matchedSources = [];
        let answerText = "";

        if (q.includes('endometriosis') || q.includes('laparoscopy') || q.includes('pelvic')) {
          matchedSources = DEMO_RESEARCH_PAPERS.filter(p => p.category === 'Endometriosis');
          answerText = "Current scientific consensus emphasizes that endometriosis is a multi-system inflammatory condition that cannot be ruled out by normal transvaginal ultrasonography alone. Superficial peritoneal lesions and early-stage disease are frequently invisible on standard scans. Clinical guidelines recommend specialized multidisciplinary referral, pelvic floor physical therapy for secondary myofascial spasm, and laparoscopic surgical excision when indicated by clinical symptoms.";
        } else if (q.includes('pcos') || q.includes('inositol') || q.includes('insulin') || q.includes('androgen')) {
          matchedSources = DEMO_RESEARCH_PAPERS.filter(p => p.category === 'PCOS');
          answerText = "The 2023 International Evidence-Based Guidelines indicate that PCOS diagnosis in adults requires two out of three Rotterdam criteria: irregular menstrual cycles, biochemical/clinical hyperandrogenism, or polycystic ovaries on ultrasound. The latest recommendations emphasize that up to 95% of individuals experience underlying insulin resistance. Randomized trials support the use of myo-inositol to D-chiro-inositol in a 40:1 ratio alongside balanced dietary and lifestyle approaches as an effective metabolic intervention.";
        } else if (q.includes('iron') || q.includes('ferritin') || q.includes('fatigue') || q.includes('heavy period')) {
          matchedSources = DEMO_RESEARCH_PAPERS.filter(p => p.id === 'res_004');
          answerText = "Clinical literature documents that heavy menstrual bleeding is a primary driver of non-anemic iron deficiency (serum ferritin < 30 ng/mL). Routine Complete Blood Count (CBC) tests measuring only Hemoglobin frequently miss iron depletion, despite patients experiencing significant cognitive fatigue, brain fog, and exercise intolerance. Testing serum ferritin is essential for identifying tissue-level iron deficit.";
        } else if (q.includes('pmdd') || q.includes('mood') || q.includes('neurosteroid') || q.includes('mental')) {
          matchedSources = DEMO_RESEARCH_PAPERS.filter(p => p.id === 'res_003');
          answerText = "Recent neuroimaging studies demonstrate that Premenstrual Dysphoric Disorder (PMDD) is primarily driven by abnormal brain GABA-A receptor sensitivity to natural physiological fluctuations of allopregnanolone, rather than an absolute excess or deficiency of circulating estrogen or progesterone. Targeted interventions such as luteal-phase SSRIs or neurosteroid modulators restore normal GABAergic signaling in responsive patients.";
        } else {
          matchedSources = [DEMO_RESEARCH_PAPERS[0], DEMO_RESEARCH_PAPERS[1]];
          answerText = "In evidence-based women's healthcare, longitudinal symptom tracking and objective clinical metrics significantly shorten diagnostic delays. Research highlights the critical importance of validating patient-reported symptom trajectories and utilizing evidence-grounded clinical pathways tailored to individual hormonal and metabolic profiles.";
        }

        return {
          answer: answerText,
          sources: matchedSources.map(s => ({
            id: s.id,
            title: s.title,
            authors: s.authors.slice(0, 2).join(', ') + (s.authors.length > 2 ? ' et al.' : ''),
            journal: s.journal,
            year: s.year,
            doi: s.doi,
            url: s.url,
            evidenceClassification: s.evidenceClassification,
            relevantPassage: s.shortSummary
          })),
          confidenceScore: 0.96,
          disclaimer: "Informational summary synthesized from peer-reviewed publications. Not intended as medical diagnosis or direct treatment recommendation."
        };
      }
      throw err;
    }
  }
};

export default aiService;
