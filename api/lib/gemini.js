/**
 * Vericove AI Symptom Intelligence - Gemini 3.8 Flash Synthesis (Phase 2.3)
 *
 * Synthesizes genuine biomedical literature from PubMed with patient symptom context
 * using Google Gemini 3.8 Flash with strict evidence grounding and medical safety constraints.
 *
 * Negative Constraints:
 * - Strictly non-diagnostic: No medical diagnoses, probability/risk scores, or prescriptions.
 * - Strict evidence grounding: Only cite PMIDs present in the retrieved PubMed records.
 * - Zero hallucinated citations or synthetic papers.
 * - Zero logging of symptom descriptions, abstracts, prompts, API keys, or outputs.
 */

import { GoogleGenAI } from '@google/genai';

export const GEMINI_DISCLAIMER =
  'This synthesis is generated by Google Gemini for educational research exploration only. It is strictly non-diagnostic and does not replace evaluation by a qualified healthcare professional. Do not alter any medical regimen based on this content.';

const SYSTEM_INSTRUCTION = `You are an educational medical research synthesis assistant for Vericove, an evidence-grounded women's health platform.
Your task is to synthesize verified biomedical research retrieved from NCBI PubMed in relation to user-reported symptoms.

STRICT MEDICAL SAFETY RULES:
1. NON-DIAGNOSTIC: You must NEVER provide differential diagnoses, suggest specific disease probabilities or likelihood scores (e.g. "70% chance of endometriosis"), or diagnose any condition.
2. NO PRESCRIPTIONS OR TREATMENTS: Do not recommend prescription drugs, dosages, off-label therapies, or clinical treatment regimens.
3. GROUNDING & EVIDENCE INTEGRITY:
   - You may ONLY cite PubMed records that are explicitly provided in the EVIDENCE LIST below.
   - For every citation in relevantClinicalResearch, the pmid MUST exactly match a PMID from the provided evidence.
   - Do NOT invent, hallucinate, extrapolate, or reference any external PMIDs, author names, or paper titles not in the evidence list.
   - If ZERO evidence records are provided, relevantClinicalResearch MUST be an empty array []. You must explain general biological context and explicitly note in studyLimitations that no direct PubMed literature was identified for this query.
4. TONE & SCOPE: Maintain an objective, compassionate, and educational tone. Focus on physiological mechanisms and structured questions the user can discuss with their physician.

You MUST respond strictly with a valid JSON object matching the requested schema.`;

const RESPONSE_SCHEMA = {
  type: 'object',
  properties: {
    patternsAndBiologicalContext: {
      type: 'string',
      description: 'Educational explanation of potential biological mechanisms, endocrine pathways, or physiological interactions related to the symptoms.'
    },
    relevantClinicalResearch: {
      type: 'array',
      description: 'Synthesized findings strictly grounded in the provided PubMed records. Empty if no records provided.',
      items: {
        type: 'object',
        properties: {
          pmid: { type: 'string', description: 'PubMed ID matching one of the provided records.' },
          citation: { type: 'string', description: 'Author et al., Year, Journal.' },
          keyFinding: { type: 'string', description: 'Concise educational summary of what the study reported.' }
        },
        required: ['pmid', 'citation', 'keyFinding']
      }
    },
    consultationQuestions: {
      type: 'array',
      description: 'Structured, non-prescriptive talking points for the user to explore with a healthcare provider.',
      items: { type: 'string' }
    },
    studyLimitations: {
      type: 'string',
      description: 'Transparent notes on evidence limitations, sample cohorts, abstract-only constraints, or missing literature.'
    }
  },
  required: [
    'patternsAndBiologicalContext',
    'relevantClinicalResearch',
    'consultationQuestions',
    'studyLimitations'
  ]
};

/**
 * Builds the user prompt containing symptom context and genuine PubMed evidence records.
 */
function buildUserPrompt(symptomData, pubMedRecords) {
  const { symptom, duration, severity } = symptomData;
  const hasRecords = Array.isArray(pubMedRecords) && pubMedRecords.length > 0;

  let evidenceText = 'None (Literature search returned zero matching records).';
  if (hasRecords) {
    evidenceText = pubMedRecords
      .map((r, i) => {
        const authors = r.authors?.length ? r.authors.slice(0, 3).join(', ') : 'Authors not listed';
        const abstractSnippet = r.abstract ? r.abstract.slice(0, 1500) : 'Abstract not available (Citation only)';
        return `[Record ${i + 1}]
PMID: ${r.pmid}
Title: ${r.title}
Authors: ${authors}
Journal: ${r.journal || 'Not specified'} (${r.pubDate || 'Year unknown'})
Type: ${r.evidenceType || 'Abstract'}
Abstract / Summary:
${abstractSnippet}`;
      })
      .join('\n\n---\n\n');
  }

  return `PATIENT OBSERVATION CONTEXT:
- Reported Symptom: ${symptom}
- Duration: ${duration || 'Unspecified'}
- Severity: ${severity || 'Moderate'}

RETRIEVED PUBMED EVIDENCE LIST:
${evidenceText}

INSTRUCTIONS:
1. Synthesize the biological context and physiological pathways.
2. Ground your clinical research findings strictly in the provided records above (citing exact PMIDs).
3. If no evidence records are provided, leave relevantClinicalResearch as an empty array [] and explicitly note the lack of literature in studyLimitations.
4. Provide constructive, non-prescriptive questions for a doctor consultation.
5. Detail study limitations transparently.`;
}

/**
 * Validates and sanitizes Gemini output, ensuring that all cited PMIDs are valid members of the retrieved set.
 */
function validateAndSanitizeResponse(rawOutput, validPmidSet) {
  let parsed;
  if (typeof rawOutput === 'object' && rawOutput !== null) {
    parsed = rawOutput;
  } else if (typeof rawOutput === 'string') {
    try {
      parsed = JSON.parse(rawOutput);
    } catch {
      return { error: { code: 'GEMINI_PARSE_ERROR', message: 'Failed to parse Gemini structured JSON output.' } };
    }
  } else {
    return { error: { code: 'GEMINI_INVALID_OUTPUT', message: 'Gemini returned an unexpected response structure.' } };
  }

  const {
    patternsAndBiologicalContext,
    relevantClinicalResearch,
    consultationQuestions,
    studyLimitations
  } = parsed;

  if (typeof patternsAndBiologicalContext !== 'string' || !patternsAndBiologicalContext.trim()) {
    return { error: { code: 'GEMINI_SCHEMA_ERROR', message: 'Missing patternsAndBiologicalContext.' } };
  }
  if (!Array.isArray(relevantClinicalResearch)) {
    return { error: { code: 'GEMINI_SCHEMA_ERROR', message: 'relevantClinicalResearch must be an array.' } };
  }
  if (!Array.isArray(consultationQuestions)) {
    return { error: { code: 'GEMINI_SCHEMA_ERROR', message: 'consultationQuestions must be an array.' } };
  }
  if (typeof studyLimitations !== 'string' || !studyLimitations.trim()) {
    return { error: { code: 'GEMINI_SCHEMA_ERROR', message: 'Missing studyLimitations.' } };
  }

  // Strict PMID Grounding: Filter out any citations referencing PMIDs not in the retrieved PubMed set
  const validatedResearch = [];
  for (const item of relevantClinicalResearch) {
    if (!item || typeof item !== 'object') continue;
    const pmid = String(item.pmid || '').trim();
    if (!pmid || !validPmidSet.has(pmid)) {
      // Drop hallucinated or unverified PMID
      continue;
    }
    validatedResearch.push({
      pmid,
      citation: String(item.citation || '').trim(),
      keyFinding: String(item.keyFinding || '').trim()
    });
  }

  // Filter consultation questions to non-empty strings
  const validatedQuestions = consultationQuestions
    .map(q => String(q || '').trim())
    .filter(Boolean);

  return {
    data: {
      patternsAndBiologicalContext: patternsAndBiologicalContext.trim(),
      relevantClinicalResearch: validatedResearch,
      consultationQuestions: validatedQuestions,
      studyLimitations: studyLimitations.trim(),
      disclaimer: GEMINI_DISCLAIMER
    }
  };
}

/**
 * Synthesizes biomedical research and symptom observation using Google Gemini 3.8 Flash.
 *
 * @param {object} symptomData - { symptom, duration, severity }
 * @param {Array} pubMedRecords - Array of genuine PubMed record objects from queryPubMed
 * @param {object} [options] - Optional overrides for testing/mocks
 * @returns {Promise<object>} { data?: object, error?: object }
 */
export async function synthesizeResearch(symptomData, pubMedRecords = [], options = {}) {
  const apiKey = options.apiKey || process.env.GEMINI_API_KEY;

  if (!apiKey || !apiKey.trim()) {
    return {
      error: {
        code: 'GEMINI_CONFIG_MISSING',
        message: 'Google Gemini API key (GEMINI_API_KEY) is not configured.'
      }
    };
  }

  const model = options.model || process.env.GEMINI_MODEL || 'gemini-3.8-flash';
  const validPmidSet = new Set((pubMedRecords || []).map(r => String(r.pmid)));
  const userPrompt = buildUserPrompt(symptomData, pubMedRecords);

  let timer;
  try {
    const OVERALL_TIMEOUT_MS = options.overallTimeoutMs || 11500;
    const timeoutPromise = new Promise((_, reject) => {
      timer = setTimeout(() => {
        const err = new Error(`Gemini synthesis operation timed out after ${OVERALL_TIMEOUT_MS}ms`);
        err.name = 'TimeoutError';
        reject(err);
      }, OVERALL_TIMEOUT_MS);
      if (typeof timer.unref === 'function') timer.unref();
    });

    const client =
      options.client ||
      new GoogleGenAI({
        apiKey,
        httpOptions: {
          timeout: 5000,
          retryOptions: {
            attempts: 2,
            initialDelay: 1.2,
            jitter: 0.5,
            httpStatusCodes: [429, 503]
          }
        }
      });

    const generatePromise = client.models.generateContent({
      model,
      contents: userPrompt,
      config: {
        systemInstruction: SYSTEM_INSTRUCTION,
        responseMimeType: 'application/json',
        responseSchema: RESPONSE_SCHEMA,
        temperature: 0.2
      }
    });

    const response = await Promise.race([generatePromise, timeoutPromise]);
    if (timer) clearTimeout(timer);
    const responseText = response.text || response.candidates?.[0]?.content?.parts?.[0]?.text;

    if (!responseText) {
      return {
        error: {
          code: 'GEMINI_EMPTY_RESPONSE',
          message: 'Gemini returned an empty response.'
        }
      };
    }

    const validationResult = validateAndSanitizeResponse(responseText, validPmidSet);
    if (validationResult.error) {
      return { error: validationResult.error };
    }

    return {
      data: {
        ...validationResult.data,
        model
      }
    };
  } catch (err) {
    if (err.name === 'TimeoutError' || err.message?.includes('timed out')) {
      return {
        error: {
          code: 'GEMINI_TIMEOUT',
          message: 'Gemini synthesis request timed out.'
        }
      };
    }
    if (err.status === 429 || err.message?.includes('429') || err.message?.includes('quota')) {
      return {
        error: {
          code: 'GEMINI_RATE_LIMITED',
          message: 'Gemini rate limit or quota exceeded. Please try again later.'
        }
      };
    }
    if (err.status === 503 || err.message?.includes('503') || err.message?.includes('high demand') || err.message?.includes('UNAVAILABLE')) {
      return {
        error: {
          code: 'GEMINI_UNAVAILABLE',
          message: 'Google Gemini service is temporarily unavailable.'
        }
      };
    }
    return {
      error: {
        code: 'GEMINI_API_ERROR',
        message: 'An error occurred while communicating with Google Gemini API.'
      }
    };
  } finally {
    if (timer) clearTimeout(timer);
  }
}

